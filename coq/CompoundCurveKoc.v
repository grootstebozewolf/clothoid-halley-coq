(* §1  Frame transforms: system 2000 <-> local coordinate system.             *)
(*                                                                            *)
(* Koc eqs (1),(2): survey point (Y,X) in the national grid maps to (x,y) in  *)
(* the local design frame with origin (Y0,X0) and rotation beta.  Eqs (42),   *)
(* (43) are the inverse used to send the chosen design variant back to the    *)
(* grid for setting out.                                                      *)
(*                                                                            *)
(* CONVENTION NOTE: the grid coordinates follow the papers' surveying (Y,X)   *)
(* ordering -- Y is the easting-like abscissa, X the northing-like ordinate   *)
(* of the Polish "system 2000" -- NOT the usual mathematical (X,Y).  The      *)
(* lemmas are order-agnostic (they never compare the two axes), but readers   *)
(* matching them against the papers should keep the (Y,X) order in mind.      *)
(* -------------------------------------------------------------------------- *)

Definition koc_local_x (Y0 X0 beta Y X : R) : R :=
  (Y - Y0) * cos beta + (X - X0) * sin beta.

Definition koc_local_y (Y0 X0 beta Y X : R) : R :=
  - (Y - Y0) * sin beta + (X - X0) * cos beta.

Definition koc_global_Y (Y0 X0 beta x y : R) : R :=
  Y0 + x * cos beta - y * sin beta.

Definition koc_global_X (Y0 X0 beta x y : R) : R :=
  X0 + x * sin beta + y * cos beta.

(* Round-trip grid -> local -> grid is the identity. *)
Theorem koc_roundtrip_global_local :
  forall Y0 X0 beta Y X,
    koc_global_Y Y0 X0 beta (koc_local_x Y0 X0 beta Y X)
                            (koc_local_y Y0 X0 beta Y X) = Y /\
    koc_global_X Y0 X0 beta (koc_local_x Y0 X0 beta Y X)
                            (koc_local_y Y0 X0 beta Y X) = X.
Proof.
  intros Y0 X0 beta Y X.
  unfold koc_global_Y, koc_global_X, koc_local_x, koc_local_y.
  pose proof (sin2_cos2 beta) as H. unfold Rsqr in H.
  split.
  - replace (Y0 + ((Y - Y0) * cos beta + (X - X0) * sin beta) * cos beta
             - (- (Y - Y0) * sin beta + (X - X0) * cos beta) * sin beta)
      with (Y0 + (Y - Y0) * (sin beta * sin beta + cos beta * cos beta))
      by ring.
    rewrite H. ring.
  - replace (X0 + ((Y - Y0) * cos beta + (X - X0) * sin beta) * sin beta
             + (- (Y - Y0) * sin beta + (X - X0) * cos beta) * cos beta)
      with (X0 + (X - X0) * (sin beta * sin beta + cos beta * cos beta))
      by ring.
    rewrite H. ring.
Qed.

(* Round-trip local -> grid -> local is the identity. *)
Theorem koc_roundtrip_local_global :
  forall Y0 X0 beta x y,
    koc_local_x Y0 X0 beta (koc_global_Y Y0 X0 beta x y)
                           (koc_global_X Y0 X0 beta x y) = x /\
    koc_local_y Y0 X0 beta (koc_global_Y Y0 X0 beta x y)
                           (koc_global_X Y0 X0 beta x y) = y.
Proof.
  intros Y0 X0 beta x y.
  unfold koc_global_Y, koc_global_X, koc_local_x, koc_local_y.
  pose proof (sin2_cos2 beta) as H. unfold Rsqr in H.
  split.
  - replace ((Y0 + x * cos beta - y * sin beta - Y0) * cos beta
             + (X0 + x * sin beta + y * cos beta - X0) * sin beta)
      with (x * (sin beta * sin beta + cos beta * cos beta)) by ring.
    rewrite H. ring.
  - replace (- (Y0 + x * cos beta - y * sin beta - Y0) * sin beta
             + (X0 + x * sin beta + y * cos beta - X0) * cos beta)
      with (y * (sin beta * sin beta + cos beta * cos beta)) by ring.
    rewrite H. ring.
Qed.

(* The transform is an isometry: squared distances are preserved, so
   chainage, gauge and clearance computations agree in both frames. *)
Theorem koc_to_local_isometry :
  forall Y0 X0 beta Y1 X1 Y2 X2,
    dist_sq (mkPoint (koc_local_x Y0 X0 beta Y1 X1)
                     (koc_local_y Y0 X0 beta Y1 X1))
            (mkPoint (koc_local_x Y0 X0 beta Y2 X2)
                     (koc_local_y Y0 X0 beta Y2 X2))
    = dist_sq (mkPoint Y1 X1) (mkPoint Y2 X2).
Proof.
  intros Y0 X0 beta Y1 X1 Y2 X2.
  unfold dist_sq, koc_local_x, koc_local_y; simpl.
  pose proof (sin2_cos2 beta) as H. unfold Rsqr in H.
  replace (((Y1 - Y0) * cos beta + (X1 - X0) * sin beta
            - ((Y2 - Y0) * cos beta + (X2 - X0) * sin beta))
           * ((Y1 - Y0) * cos beta + (X1 - X0) * sin beta
              - ((Y2 - Y0) * cos beta + (X2 - X0) * sin beta))
           + (- (Y1 - Y0) * sin beta + (X1 - X0) * cos beta
              - (- (Y2 - Y0) * sin beta + (X2 - X0) * cos beta))
             * (- (Y1 - Y0) * sin beta + (X1 - X0) * cos beta
                - (- (Y2 - Y0) * sin beta + (X2 - X0) * cos beta)))
    with (((Y1 - Y2) * (Y1 - Y2) + (X1 - X2) * (X1 - X2))
          * (sin beta * sin beta + cos beta * cos beta)) by ring.
  rewrite H. ring.
Qed.

(* -------------------------------------------------------------------------- *)
(* §2  Clothoid transition end conditions (Koc §2).                           *)
(*                                                                            *)
(* The clothoid TC1 has linear curvature k(l) = l/(R L) over l in [0,L].      *)
(* Its tangent angle is the integral theta(l) = l^2/(2 R L); the paper's      *)
(* pivotal observation is that the END angle theta(L) = L/(2R) is             *)
(* TYPE-INDEPENDENT -- every standard transition family shares it -- so the   *)
(* downstream tangency bookkeeping (eq (7): s_K1 = tan(theta(L) - alpha/2))   *)
(* never depends on which family the designer picked.                        *)
(* -------------------------------------------------------------------------- *)

Definition koc_clothoid_curvature (Rr L l : R) : R := l / (Rr * L).

Definition koc_clothoid_angle (Rr L l : R) : R := / (2 * Rr * L) * (l * l).

(* theta really is the antiderivative of k: at every l the derivative of the
   angle function is the curvature.  (This is the "theta = integral of k"
   step the paper takes silently.) *)
Theorem koc_clothoid_angle_deriv :
  forall Rr L l,
    Rr <> 0 -> L <> 0 ->
    derivable_pt_lim (koc_clothoid_angle Rr L) l
                     (koc_clothoid_curvature Rr L l).
Proof.
  intros Rr L l HR HL.
  unfold koc_clothoid_angle, koc_clothoid_curvature.
  assert (Hsq : derivable_pt_lim (fun x => x * x) l (l + l)).
  { pose proof (derivable_pt_lim_mult id id l 1 1
                  (derivable_pt_lim_id l) (derivable_pt_lim_id l)) as H.
    unfold id in H.
    replace (l + l) with (1 * l + l * 1) by ring. exact H. }
  pose proof (derivable_pt_lim_scal (fun x => x * x) (/ (2 * Rr * L)) l
                (l + l) Hsq) as H.
  replace (l / (Rr * L)) with (/ (2 * Rr * L) * (l + l)) by (field; lra).
  exact H.
Qed.

(* Start conditions: zero curvature and zero angle at the straight. *)
Lemma koc_clothoid_start :
  forall Rr L,
    Rr <> 0 -> L <> 0 ->
    koc_clothoid_curvature Rr L 0 = 0 /\ koc_clothoid_angle Rr L 0 = 0.
Proof.
  intros. unfold koc_clothoid_curvature, koc_clothoid_angle.
  split; field; lra.
Qed.

(* End curvature: exactly the arc's 1/R -- the C0 curvature join to CA1. *)
Lemma koc_clothoid_end_curvature :
  forall Rr L,
    Rr <> 0 -> L <> 0 ->
    koc_clothoid_curvature Rr L L = / Rr.
Proof.
  intros. unfold koc_clothoid_curvature. field; lra.
Qed.

(* End angle: theta(L) = L / (2 R) -- the paper's type-independent constant
   that all downstream tangency formulas (eqs (7), (22), (30)) consume. *)
Theorem koc_clothoid_end_angle :
  forall Rr L,
    Rr <> 0 -> L <> 0 ->
    koc_clothoid_angle Rr L L = L / (2 * Rr).
Proof.
  intros. unfold koc_clothoid_angle. field; lra.
Qed.

