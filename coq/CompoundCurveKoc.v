(* §6  Worked example: the exact 3-4-5 instance.                              *)
(*                                                                            *)
(* Slope s = 3/4 gives 1 + s^2 = 25/16 = (5/4)^2, so u = 5/4 and every        *)
(* quantity is rational: from tangency point K = (0,0) with R = 5 the centre  *)
(* is S = (3,-4) (a 3-4-5 triangle), and setting out d = 2 along the tangent  *)
(* lands at M = (8/5, 6/5).  A concrete, sqrt-free witness that §3-§5 are     *)
(* non-vacuous, in the style of the corpus's oracle galleries.                *)
(* -------------------------------------------------------------------------- *)

Example koc_example_345_center :
  dist_sq (mkPoint 3 (-4)) (mkPoint 0 0) = 5 * 5 /\
  (3 - 0) * 1 + ((-4) - 0) * (3 / 4) = 0.
Proof.
  unfold dist_sq; simpl. split; lra.
Qed.

Example koc_example_345_center_is_koc :
  mkPoint (0 + (3/4) * 5 / (5/4)) (0 - 5 / (5/4)) = mkPoint 3 (-4).
Proof.
  f_equal; lra.
Qed.

Example koc_example_345_setout :
  let M := mkPoint (0 + 2 / (5/4)) (0 + (3/4) * 2 / (5/4)) in
  (py M - 0) = (3/4) * (px M - 0) /\ dist_sq M (mkPoint 0 0) = 2 * 2.
Proof.
  cbv zeta. unfold dist_sq; simpl. split; lra.
Qed.

