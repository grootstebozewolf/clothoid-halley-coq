   The analytic core of compound-curve railway alignment design, after

     W. Koc, "Design of compound curves adapted to the satellite
     measurements", The Archives of Transport 34(2), 2015, 37-49
     (doi:10.5604/08669546.1169211).

   THE REAL-WORLD PROBLEM.  Mobile GNSS surveys (antennas on a rail trailer,
   Poland's ASG-EUPOS network) deliver the as-built track axis as coordinates
   in the national grid ("system 2000", EPSG:2176-2180).  On degraded lines
   the track is often so deformed that the original design straights ("main
   directions") cannot be recovered, so re-alignment cannot use the classic
   symmetric pattern (transition - single arc - transition); the designer
   must connect the two surveyed directions with a COMPOUND CURVE (EN
   13803-1): two circular arcs of different radii R1, R2 joined by three
   transition curves TC1-TC3.  Koc's method writes the WHOLE system as
   closed-form equations in a local frame, so that alignment variants are
   generated by substituting design values (radii, transition lengths)
   instead of redrawing CAD geometry.  Every equation below is load-bearing
   in that pipeline -- and each has a concrete failure mode when implemented
   naively in floating point (frame drift between survey and design, a
   tangency center placed on the wrong side of the track producing a kink a
   train cannot run, a mis-set transition angle breaking the superelevation
   ramp at line speed).

   WHAT IS MECHANISED (paper eq |-> lemma):

     (1),(2) + (42),(43)  global<->local frame transform round-trips
                          (`koc_roundtrip_*`) and its isometry
                          (`koc_to_local_isometry`) -- survey points and
                          design geometry live in different frames; these
                          are the exactness conditions for moving between
                          them with zero information loss.
     Sec. 2 (clothoid)    linear curvature k(l) = l/(R L) integrates to the
                          tangent angle theta(l) = l^2/(2 R L)
                          (`koc_clothoid_angle_deriv`), with the end
                          conditions k(L) = 1/R and the type-independent
                          end angle theta(L) = L/(2R)
                          (`koc_clothoid_end_*`) that the whole tangency
                          bookkeeping of the paper rests on.
     (8),(9) / (23),(24)  the arc centre lies at distance R along the
                          normal of the tangency point
                          (`koc_center_on_normal`) -- stated sqrt-free by
                          carrying u > 0, u^2 = 1 + s^2.
     (31),(32)            the point of a circle where the tangent has a
                          prescribed slope (`koc_slope_point_on_circle`) --
                          where arc CA2 must end so that TC3 can land on
                          the second main direction.
     (11),(12) / (14),(15) setting out along a tangent: the point at
                          distance d along the slope-s direction
                          (`koc_tangent_setout`), and the surveyor's
                          tangent length d = R tan(alpha/2)
                          (`koc_tangent_length`).
     Worked example       an exact 3-4-5 instance (s = 3/4, u = 5/4,
                          R = 5): centre (3,-4) from K = (0,0), all checks
                          by rational arithmetic -- the corpus-style
                          concrete witness that the formulas are not
                          vacuous.

   All statements are sqrt-free (squared distances, normalisation carried
   as a hypothesis), matching the corpus convention that lets every proof
   close by `ring`/`field`/`nra` and keeps the axiom footprint at the
   standard classical-reals trio.

   No `Admitted`, no `Axiom`, no `Parameter`.

