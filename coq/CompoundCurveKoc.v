(* §3  Arc centre from the tangency point (Koc eqs (8),(9) and (23),(24)).    *)
(*                                                                            *)
(* At the transition end K the tangent has slope s.  The arc centre S must    *)
(* lie on the normal at K, at distance R.  The paper divides by sqrt(1+s^2);  *)
(* we carry the normaliser as a hypothesis u > 0, u^2 = 1 + s^2, so the       *)
(* whole statement is rational in the inputs and closes by field/nra.        *)
(* A sign error here is the classic alignment bug: the centre lands on the    *)
(* wrong side of the track and the "arc" meets the transition in a kink.      *)
(*                                                                            *)
(* SIGN CONVENTION: the normal offset direction is (s, -1)/u -- the centre    *)
(* BELOW the curve (Koc's Figs 2-3: system convex upward, positive            *)
(* curvature).  The mirrored convention (-s, 1)/u (centre above) appears in   *)
(* §4 as the point-from-centre direction, and both are exercised by the       *)
(* 3-4-5 examples.  This is intentional -- do NOT "fix" the sign; flipping    *)
(* it here silently moves every centre to the wrong side of the track.        *)
(* -------------------------------------------------------------------------- *)

Theorem koc_center_on_normal :
  forall xK yK s Rr u,
    0 < u -> u * u = 1 + s * s ->
    let S := mkPoint (xK + s * Rr / u) (yK - Rr / u) in
    let K := mkPoint xK yK in
    (* distance: |SK|^2 = R^2 *)
    dist_sq S K = Rr * Rr /\
    (* perpendicularity: (S-K) . (1,s) = 0, i.e. SK is the normal at K *)
    (px S - px K) * 1 + (py S - py K) * s = 0.
Proof.
  intros xK yK s Rr u Hu Husq S K.
  assert (Hne : u <> 0) by lra.
  unfold S, K, dist_sq; simpl.
  split.
  - transitivity (Rr * Rr * (1 + s * s) / (u * u)).
    + field. exact Hne.
    + rewrite <- Husq. field. exact Hne.
  - field. exact Hne.
Qed.

(* -------------------------------------------------------------------------- *)
(* §4  The prescribed-slope point of a circle (Koc eqs (31),(32)).            *)
(*                                                                            *)
(* Conversely: given the centre S and a target tangent slope s (dictated by   *)
(* where transition TC3 must take over), the point K on the circle whose      *)
(* tangent has slope s sits at S + (R/u) * (-s, 1).  This is how the paper    *)
(* locates the END of arc CA2 -- the handover point to the last transition.   *)
(* -------------------------------------------------------------------------- *)

Theorem koc_slope_point_on_circle :
  forall xS yS s Rr u,
    0 < u -> u * u = 1 + s * s ->
    let K := mkPoint (xS - s * Rr / u) (yS + Rr / u) in
    let S := mkPoint xS yS in
    (* K is on the circle of radius R about S *)
    dist_sq K S = Rr * Rr /\
    (* the radius SK is perpendicular to the slope-s direction, so the
       tangent to the circle at K has exactly slope s *)
    (px K - px S) * 1 + (py K - py S) * s = 0.
Proof.
  intros xS yS s Rr u Hu Husq K S.
  assert (Hne : u <> 0) by lra.
  unfold K, S, dist_sq; simpl.
  split.
  - transitivity (Rr * Rr * (1 + s * s) / (u * u)).
    + field. exact Hne.
    + rewrite <- Husq. field. exact Hne.
  - field. exact Hne.
Qed.

(* -------------------------------------------------------------------------- *)
(* §5  Setting out along a tangent (Koc eqs (11),(12),(14),(15)).             *)
(*                                                                            *)
(* Moving distance d from K along the direction of slope s lands at           *)
(* M = K + (d/u)(1, s).  With d = R tan(alpha/2) this is the surveyor's       *)
(* tangent-length step: M is the intersection of the two tangents of an arc   *)
(* with turning angle alpha (the point the paper calls M1), the stake every   *)
(* setting-out crew places first.                                             *)
(* -------------------------------------------------------------------------- *)

Theorem koc_tangent_setout :
  forall xK yK s d u,
    0 < u -> u * u = 1 + s * s ->
    let M := mkPoint (xK + d / u) (yK + s * d / u) in
    let K := mkPoint xK yK in
    (* M lies on the slope-s line through K *)
    (py M - py K) = s * (px M - px K) /\
    (* at squared distance exactly d^2 *)
    dist_sq M K = d * d.
Proof.
  intros xK yK s d u Hu Husq M K.
  assert (Hne : u <> 0) by lra.
  unfold M, K, dist_sq; simpl.
  split.
  - field. exact Hne.
  - transitivity (d * d * (1 + s * s) / (u * u)).
    + field. exact Hne.
    + rewrite <- Husq. field. exact Hne.
Qed.

(* The tangent-length instance: d = R tan(alpha/2) gives |KM|^2 =
   R^2 tan^2(alpha/2) -- Koc's |K1 M1| = R1 tan(alpha1/2). *)
Corollary koc_tangent_length :
  forall xK yK s Rr alpha u,
    0 < u -> u * u = 1 + s * s ->
    dist_sq (mkPoint (xK + Rr * tan (alpha / 2) / u)
                     (yK + s * (Rr * tan (alpha / 2)) / u))
            (mkPoint xK yK)
    = (Rr * tan (alpha / 2)) * (Rr * tan (alpha / 2)).
Proof.
  intros xK yK s Rr alpha u Hu Husq.
  pose proof (koc_tangent_setout xK yK s (Rr * tan (alpha / 2)) u Hu Husq)
    as [_ Hd].
  exact Hd.
Qed.

